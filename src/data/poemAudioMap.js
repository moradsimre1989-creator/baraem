/** يوحّد الكلمة للبحث: يحذف التشكيل وعلامات الترقيم */
function key(word) {
  return String(word)
    .replace(/[ً-ْٰـ]/g, "")
    .replace(/[^ء-ي]/g, "");
}

/**
 * الشطر الذي وردت فيه كلمة، بتوقيته في تسجيل المعلّمة.
 * يُعاد null إن لم تُعرف الكلمة — وعندها يعود المكوّن إلى النطق الآلي بدل
 * أن يشغّل شطراً خاطئاً.
 */
export function segmentForWord(word) {
  const k = key(word);
  if (!k) return null;
  return POEM_SEGMENTS.find((seg) => seg.text.split(/\s+/).some((w) => key(w) === k)) ?? null;
}

/** الشطر بحسب رقم البيت وموضعه — للتظليل أثناء القراءة */
export function segmentAt(line, part) {
  return POEM_SEGMENTS.find((s) => s.line === line && s.part === part) ?? null;
}
